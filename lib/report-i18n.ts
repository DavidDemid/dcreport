const templates = [...templatePairs].sort(([a], [b]) => b.replace(/\{\d+\}/g, "").length - a.replace(/\{\d+\}/g, "").length).map(([english, russian]) => {
  const indexes: number[] = [];
  const pattern = english.split(/(\{\d+\})/).map((part) => {
    if (/^\{\d+\}$/.test(part)) { indexes.push(Number(part.slice(1, -1))); return "([\\s\\S]*?)"; }
    return part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  }).join("");
  return { pattern: new RegExp(`^${pattern}$`), russian, indexes };
});

function translateTrimmed(text: string): string {
  if (Object.hasOwn(russian, text)) return russian[text];
  const days = text.match(/^([\d\s,.\u00a0\u202f]+) days?$/);
  if (days) {
    const n = Number(days[1].replace(/[^\d]/g, ""));
    const suffix = n % 10 === 1 && n % 100 !== 11 ? "день" : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? "дня" : "дней";
    return `${days[1]} ${suffix}`;
  }
  const duration = text.match(/^([\d.,\s]+)( min| h| d)$/);
  if (duration) return `${duration[1]} ${russian[duration[2].trim()]}`;
  const part = text.match(/^(.*?) (\(\d+\/\d+\))$/);
  if (part) return `${translateTrimmed(part[1])} ${part[2]}`;
  for (const template of templates) {
    const match = text.match(template.pattern);
    if (match) return template.russian.replace(/\{(\d+)\}/g, (_, index: string) => translateTrimmed(match[template.indexes.indexOf(Number(index)) + 1]));
  }
  for (const separator of [" / ", " | ", "; ", ": "]) {
    if (!text.includes(separator)) continue;
    const parts = text.split(separator);
    const translated = parts.map((part) => translateTrimmed(part));
    if (translated.some((part, index) => part !== parts[index])) return translated.join(separator);
  }
  return text;
}

export function translateReportText(text: string, language: ReportLanguage): string {
  if (language !== "ru" || !text.trim()) return text;
  const trimmed = text.trim();
  const start = text.length - text.trimStart().length;
  return text.slice(0, start) + translateTrimmed(trimmed) + text.slice(start + trimmed.length);
}

/** Translate presentation only: never rewrite component contracts, identifiers or filter values. */
export function translateReportNode(node: ReactNode, t: ReportTranslator): ReactNode {
  if (typeof node === "string") return t(node);
  if (Array.isArray(node)) return Children.map(node, (child) => translateReportNode(child, t));
  if (!isValidElement(node)) return node;
  const element = node as ReactElement<Record<string, unknown>>;
  if (element.props.translate === "no" || element.props["data-i18n-raw"] === true) return node;
  const props: Record<string, unknown> = {};
  if ("children" in element.props) props.children = translateReportNode(element.props.children as ReactNode, t);
  if (typeof element.type === "string") {
    for (const name of ["title", "aria-label", "aria-description", "placeholder", "alt"]) {
      if (typeof element.props[name] === "string") props[name] = t(element.props[name]);
    }
  }
  return cloneElement(element, props);
}
